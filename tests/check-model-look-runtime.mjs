import assert from "node:assert/strict";
import * as THREE from "three";
import { ModelLookRuntime } from "../src/model-look-runtime.ts";
import { defaultModelLook } from "../src/model-look.ts";
import { CardAppearance } from "../src/appearance.ts";

const runtime = new ModelLookRuntime(), original = defaultModelLook();
assert(runtime.configure(original, []));
assert(!runtime.configure(original, []), "Unchanged look does not invalidate idle frames");
assert.equal(runtime.resolve({ id: "a" }).amount, 0);
const appearance = new CardAppearance(), material = new THREE.MeshPhysicalMaterial({ transmission: .9, thickness: .12 });
appearance.register("Frosted_Polymer", material, material.clone());
const group = new THREE.Group(), mesh = new THREE.Mesh(new THREE.PlaneGeometry(2.65, 3.05), material);
mesh.userData.surface = "Frosted_Polymer"; group.add(mesh);
const vertices = [...mesh.geometry.attributes.position.array];
appearance.prepare(group); runtime.applyGroup(group, { id: "a", category: "研究" });
const config = { ...original, mode: "solid", color: "#12a594", coating: "pearl" };
runtime.configure(config, []); runtime.applyGroup(group);
assert(mesh.userData.modelLook.color.value.equals(new THREE.Color(config.color)));
assert.equal(mesh.userData.modelLook.coating.value, 3);
const returning = group.clone(true); appearance.prepare(returning); runtime.applyGroup(returning);
assert.notEqual(returning.children[0].userData.modelLook, mesh.userData.modelLook, "Returning material owns live uniforms");
runtime.applyGroup(group, { id: "b", category: "研究" });
const savedConfig = { ...original, favoriteEnabled: true, favoriteColor: "#ffc53d" };
runtime.configure(savedConfig, ["a"]); runtime.applyGroup(group); runtime.applyGroup(returning);
assert.equal(mesh.userData.modelLook.amount.value, 0, "Regular card retains original in original mode");
assert.equal(returning.children[0].userData.modelLook.amount.value, original.strength, "Returning saved card uses its original document ID");
assert(returning.children[0].userData.modelLook.color.value.equals(new THREE.Color(savedConfig.favoriteColor)));
runtime.configure(savedConfig, []); runtime.applyGroup(returning);
assert.equal(returning.children[0].userData.modelLook.amount.value, 0, "Removing favorite immediately restores regular color");
assert.equal(runtime.resolve({ id: "EMPTY", placeholder: true }).amount, 0);
const colorful = { ...original, mode: "palette" };
runtime.configure(colorful, []);
const a = runtime.resolve({ id: "stable-document", category: "研究" });
assert.equal(runtime.resolve({ id: "stable-document", category: "研究" }), a, "Repeated rows reuse cached color");
runtime.configure({ ...colorful }, []);
assert.equal(runtime.resolve({ id: "stable-document", category: "研究" }), a, "No color churn for equivalent preferences");
assert.deepEqual([...mesh.geometry.attributes.position.array], vertices, "All positions and print dimensions stay unchanged");
console.log("Model look runtime: stable cached colors, idle equality, saved priority, independent returning uniforms and unchanged geometry passed.");
