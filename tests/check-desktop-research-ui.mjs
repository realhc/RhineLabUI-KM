import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { cp, mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const run = resolve('release/document-images-test/research');
const evidence = resolve('verification/research');
const portable = join(run, 'portable');
await mkdir(run, { recursive: true }); await mkdir(evidence, { recursive: true });
await cp(resolve('release/packages/RhineLab-win32-x64'), portable, { recursive: true, filter: path => !path.split(/[\\/]/).some(part => part.toLowerCase() === 'rhinelabdata') });
let app, page; const errors = [], checks = {};
async function poll(fn, arg, timeout = 60000) {
  const until = Date.now() + timeout;
  do { if (await page.evaluate(fn, arg)) return; await page.waitForTimeout(80); } while (Date.now() < until);
  throw Error('Research UI timeout: ' + fn);
}
async function open(doc) {
  await page.locator('#search').fill(doc.title);
  await page.locator(`#documents [data-id="${doc.id}"]`).click();
  await poll(title => document.querySelector('#title')?.value === title, doc.title);
  await page.waitForTimeout(100);
}
try {
  app = await electron.launch({ executablePath: join(portable, 'RhineLab.exe'), args: ['--user-data-dir=' + join(run, 'profile')], timeout: 60000 });
  page = await app.firstWindow(); page.setDefaultTimeout(20000);
  page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 960));
  await poll(() => window.rhineReview?.stats().ready);
  if (await page.evaluate(() => window.rhineReview.stats().startup) !== 'started') await page.locator('.entry-start').click();
  await poll(() => window.rhineReview.stats().startup === 'started');
  await page.evaluate(() => window.rhineReview.archive());
  await page.locator('[data-action="search"]').click();
  await poll(() => document.querySelector('#library-overlay')?.dataset.motionState === 'open');
  const docs = await page.evaluate(async () => {
    const suffix = Date.now().toString();
    const category = await window.rhine.createCategory('研究验证' + suffix);
    const body = '# 研究起点\n\n' + '研究材料与观察。\n\n'.repeat(20) + '## 证据与联系\n\n' + '对照与记录。\n\n'.repeat(20) + '### 下一步\n\n继续验证。\n';
    const target = await window.rhine.create({ title: '阅读定位' + suffix, category: category.name, categoryId: category.id, body });
    const source = await window.rhine.create({ title: '引用来源' + suffix, category: category.name, categoryId: category.id, body: `# 引用记录\n\n[阅读材料](${target.id}.md) 包含关键观察。\n` });
    const mention = await window.rhine.create({ title: '提及材料' + suffix, category: category.name, categoryId: category.id, body: `# 旁注\n\n${target.title} 值得进一步核查。\n` });
    return { target, source, mention, body };
  });
  await open(docs.target);
  assert.equal(await page.locator('#format').isVisible(), false);
  assert(await page.locator('#archive-identity').innerText());
  await page.locator('#reading-outline-toggle').click();
  await poll(() => document.querySelectorAll('.outline-items button').length === 3);
  await page.locator('.outline-items button').nth(1).click();
  await poll(() => document.querySelector('#panes').scrollTop > 300);
  const sheet = await page.evaluate(() => {
    const preview = document.querySelector('#preview'), content = preview.querySelector('.rich-document');
    return { height: preview.getBoundingClientRect().height, needed: content.getBoundingClientRect().bottom - preview.getBoundingClientRect().top + parseFloat(getComputedStyle(preview).paddingBottom), grid: Number(document.querySelector('#document-drafting').getAttribute('height')), outline: document.querySelector('#reading-outline').getBoundingClientRect().height, viewport: document.querySelector('#panes').clientHeight };
  });
  assert(sheet.height >= sheet.needed - 1 && Math.abs(sheet.height - sheet.grid) < 1, JSON.stringify(sheet));
  assert(sheet.outline <= sheet.viewport + 1, 'Outline must fit the reading viewport');
  checks.longDocumentGrid = true;
  const position = await page.locator('#panes').evaluate(el => el.scrollTop);
  await open(docs.source);
  await page.locator('#reading-back').click();
  await poll(title => document.querySelector('#title')?.value === title, docs.target.title);
  await page.waitForTimeout(120);
  assert(Math.abs(await page.locator('#panes').evaluate(el => el.scrollTop) - position) < 5);
  checks.outlineAndPosition = true;
  await page.locator('#search').fill('对照');
  await poll(() => document.querySelector('#search-position-label')?.textContent.includes('20'));
  await page.locator('#search-next').click();
  const matchTop = await page.evaluate(() => {
    const ranges = [...CSS.highlights.get('rhine-search')];
    return ranges[1].getBoundingClientRect().top - document.querySelector('#panes').getBoundingClientRect().top;
  });
  assert(Math.abs(matchTop - 70) < 2, 'Search must scroll the actual reading container');
  checks.searchHitNavigation = true;
  await page.locator('#reading-forward').click();
  await poll(title => document.querySelector('#title')?.value === title, docs.source.title);
  await page.keyboard.press('Control+p');
  await page.locator('#reading-switcher input').fill(docs.target.title);
  await page.keyboard.press('Enter');
  await poll(title => document.querySelector('#title')?.value === title, docs.target.title);
  checks.quickSwitcher = true;
  await page.locator('#save').click();
  assert(await page.locator('#format').isVisible());
  await page.locator('#preview .tiptap').press('Control+End');
  await page.keyboard.insertText('\n[[' + docs.source.title);
  await poll(() => !!document.querySelector('.document-link-suggestions'));
  await page.keyboard.press('Enter');
  await poll(id => !!document.querySelector(`#preview a[href="${id}.md"]`), docs.source.id);
  await page.keyboard.press('Control+s');
  await poll(() => document.querySelector('#state').textContent.startsWith('已保存'));
  const saved = await page.evaluate(id => window.rhine.read(id), docs.target.id);
  assert(saved.body.includes(docs.source.id + '.md'));
  checks.wikiCompletion = true;
  await page.keyboard.insertText('临时草稿');
  await page.locator('#reading-back').click();
  await poll(() => document.querySelector('#dialog')?.open);
  await page.locator('[data-choice="cancel"]').click();
  assert.equal(await page.locator('#title').inputValue(), docs.target.title);
  assert((await page.locator('#preview .tiptap').innerText()).includes('临时草稿'));
  await page.locator('#reading-back').click();
  await poll(() => document.querySelector('#dialog')?.open);
  await page.locator('[data-choice="discard"]').click();
  await poll(title => document.querySelector('#title')?.value !== title, docs.target.title);
  checks.draftProtectedNavigation = true;
  await open(docs.source); await open(docs.target);
  await page.locator('#document-relations-toggle').click();
  await poll(id => !!document.querySelector(`.relation-document[data-relation-id="${id}"]`), docs.source.id);
  await page.locator('[data-relations-tab="mentions"]').click();
  await poll(id => !!document.querySelector(`.relation-document[data-relation-id="${id}"]`), docs.mention.id);
  await page.locator('[data-relations-tab="outgoing"]').click();
  await poll(id => !!document.querySelector(`.relation-document[data-relation-id="${id}"]`), docs.source.id);
  await page.locator('#relations-depth').selectOption('2');
  await page.locator('#relations-expand').click();
  await poll(() => document.querySelector('#graph-workspace')?.dataset.graphMode === 'local');
  assert.equal(await page.locator('#graph-depth').inputValue(), '2');
  await page.locator('#graph-global').click();
  await poll(() => document.querySelector('#graph-workspace')?.dataset.graphMode === 'global');
  await page.locator('#graph-close').click();
  await page.locator('[data-relations-tab="incoming"]').click();
  await page.screenshot({ path: join(evidence, 'reading-and-relations.png') });
  checks.backlinksMentionsAndLocalGraph = true;
  await page.locator('#document-history-open').click();
  await poll(() => !!document.querySelector('#history-list [data-history-key]'));
  await page.locator('#history-diff-mode').click();
  await poll(() => document.querySelector('#history-diff')?.textContent.includes('当前版本'));
  await page.screenshot({ path: join(evidence, 'history.png') });
  const initialHistory = await page.evaluate(id => window.rhine.listHistory(id), docs.target.id);
  const snapshots = await page.evaluate(async ({ id, entries }) => Promise.all(entries.map(entry => window.rhine.readHistory(id, entry.key))), { id: docs.target.id, entries: initialHistory });
  const originalIndex = snapshots.findIndex(version => version.body === docs.body);
  assert(originalIndex >= 0, 'Original saved body must be recoverable');
  const key = initialHistory[originalIndex].key;
  await page.locator('#history-list [data-history-key]').filter({ hasText: '' }).evaluateAll((buttons, key) => buttons.find(button => button.dataset.historyKey === key).click(), key);
  await poll(() => !document.querySelector('#history-restore')?.disabled);
  await page.locator('#history-restore').click();
  await poll(() => !document.querySelector('#document-history')?.open);
  assert.equal((await page.evaluate(id => window.rhine.read(id), docs.target.id)).body, docs.body);
  const afterHistory = await page.evaluate(id => window.rhine.listHistory(id), docs.target.id);
  assert(afterHistory.length > initialHistory.length, 'Restoring must retain the overwritten current version');
  checks.historyRestoreRetainsCurrent = true;
  await page.locator('#document-history-open').click();
  await poll(() => !document.querySelector('#history-copy')?.disabled);
  await page.locator('#history-copy').click();
  await poll(() => !document.querySelector('#document-history')?.open && document.querySelector('#title')?.value.includes('历史副本'));
  const copy = await page.evaluate(async () => { const title = document.querySelector('#title').value; return (await window.rhine.list()).documents.find(doc => doc.title === title); });
  assert(copy && copy.id !== docs.target.id);
  checks.historyCopy = true;
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1000, 720));
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#library-overlay').evaluate(el => el.scrollWidth > el.clientWidth), false);
  await page.screenshot({ path: join(evidence, 'reading-narrow.png') });
  checks.narrowLayout = true;
  assert.deepEqual(errors, []);
  await writeFile(join(evidence, 'result.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log('Research UI: reading navigation, link completion, draft protection, backlinks, local graph, history restore/copy and narrow layout passed.');
} catch (error) {
  await page?.screenshot({ path: join(evidence, 'failure.png') }).catch(() => {});
  await writeFile(join(evidence, 'failure.json'), JSON.stringify({ checks, errors, error: String(error), stack: error.stack }, null, 2));
  throw error;
} finally {
  await page?.evaluate(() => window.rhine.setDirty(false)).catch(() => {});
  await app?.close();
}
